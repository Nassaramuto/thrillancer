// Runs the ORIGINAL Claude Design (V2) world scripts headlessly and dumps the collision/landmark data used by the
// server (packages/contracts/src/world-data.ts). Does not modify the design scripts. Usage: npm run world:extract
import { chromium } from "playwright";
import fs from "node:fs";
import path from "node:path";
const dir = path.resolve("apps/web/public/design");
const REF = process.env.DESIGN_APP_JS ?? path.resolve("references/claude-design/V2 Zeitgeist cinematic animation suite/zg-app.js");
const exe = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE;
const b = await chromium.launch({ executablePath: exe, args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--no-sandbox"] });
const p = await b.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(String(e)));
await p.route("**/*", (r) => (r.request().url().startsWith("http") ? r.abort() : r.continue())); // never touch the network (CoinGecko etc.)
await p.setContent("<html><body><div id='zg-root'></div></body></html>");
await p.addScriptTag({ content: fs.readFileSync(path.resolve("scripts/vendor/three-r128.min.js"), "utf8") });
await p.evaluate(() => { window.ZG = {}; });
for (const f of ["zg-core.js", "zg-avatar.js", "zg-city.js", "zg-dest.js", "zg-dest2.js", "zg-extras.js"]) {
  await p.addScriptTag({ content: fs.readFileSync(path.join(dir, f), "utf8") });
}
// The travel table D lives in zg-app.js; take it verbatim from the reference text.
const appSrc = fs.readFileSync(REF, "utf8");
const i0 = appSrc.indexOf("const D=[");
const i1 = appSrc.indexOf("];", i0);
const dText = appSrc.slice(i0 + "const D=".length, i1 + 1);
const out = await p.evaluate((dText) => {
  const Z = window.ZG, r = (n) => Math.round(n * 1000) / 1000;
  const T = window.THREE;
  const D = new Function("return " + dText)();
  return {
    circles: Z.circles.map((c) => [r(c.x), r(c.z), r(c.r)]),
    boxes: Z.boxes.map((c) => [r(c.x0), r(c.x1), r(c.z0), r(c.z1)]),
    platforms: Z.platforms.map((c) => [r(c.x0), r(c.x1), r(c.z0), r(c.z1), r(c.h)]),
    mounds: (Z.mounds || []).map((m) => [r(m.x), r(m.z), r(m.r), r(m.h)]),
    dest: Z.dest.map((d) => ({ k: d.k, n: d.n, tag: d.tag, x: r(d.x), z: r(d.z), r: d.r, c: d.c, minor: !!d.minor })),
    travel: D.map((d) => ({ id: d.id, n: d.n, cat: d.cat, tag: d.tag, x: d.x, z: d.z, sp: d.sp, f: d.f, c: d.c })),
    interact: Z.interact.map((o) => ({ x: r(o.x), z: r(o.z), r: o.r, label: o.label })),
    bones: Z.bones.map((o) => ({ x: r(o.x), z: r(o.z) })),
    rings: (Z.rings || []).map((o) => ({ x: r(o.x), z: r(o.z) })),
    bikes: Z.bikes.map((o) => {
      const v = o.g.getWorldPosition(new T.Vector3());
      const q = o.g.getWorldQuaternion(new T.Quaternion());
      const f = new T.Vector3(0, 0, 1).applyQuaternion(q);
      const r6 = (n) => Math.round(n * 1e6) / 1e6; return [r6(v.x), r6(v.y), r6(v.z), r6(Math.atan2(f.x, f.z))];
    }),
  };
}, dText);
await b.close();
console.log("errors:", errs);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, Array.isArray(v) ? v.length : v])));
fs.writeFileSync("packages/contracts/src/world-data.ts", "// GENERATED by scripts/extract-world.mjs from the original Claude Design V2 scripts. Do not edit.\nconst worldData = " + JSON.stringify(out) + ";\nexport default worldData;\n");
console.log(JSON.stringify(out.travel.map((t) => t.id + ":" + t.sp)), JSON.stringify(out.bikes.slice(0, 3)));
